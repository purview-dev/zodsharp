using System.Text;
using Microsoft.CodeAnalysis;
using ZodSharp.SourceGenerators.Models;

namespace ZodSharp.SourceGenerators;

partial class ZodSchemaGenerator
{
	const string RegistrationNamespace = "ZodSharp.Generated";

	/// <summary>
	/// Emits the per-assembly registration (Change 5): <c>ZodSharp.Generated.{Assembly}ZodSharpSchemas.Register</c>
	/// names every generated validator directly, so registering them is trim- and AOT-safe (no attribute
	/// scanning, no <c>Activator</c>), and the generated validators register as <c>IZodUntypedValidator</c>
	/// without reflection. When Microsoft.Extensions.DependencyInjection is referenced, an
	/// <c>AddZodSharp{Assembly}Schemas()</c> extension adds the registration to the container's factory.
	/// </summary>
	static void GenerateAssemblyRegistration(
		SourceProductionContext context,
		SchemaGenerationModel model,
		IReadOnlyList<ZodSchemaDescriptor> schemas
	)
	{
		var registrable = schemas
			.Where(IsRegistrable)
			.OrderBy(static schema => schema.TargetType.AsTypeReference().ToString(), StringComparer.Ordinal)
			.ToList();

		if (registrable.Count == 0)
			return;

		var identifier = GetAssemblyIdentifier(model.Context.Capabilities.AssemblyName);
		var className = $"{identifier}ZodSharpSchemas";
		var factoryType = "global::ZodSharp.Core.IZodSchemaFactory";

		var writer = model.Context.CreateCodeWriter();
		writer.AutoGeneratedHeader();

		using (writer.BlockNamespaceScope(RegistrationNamespace))
		{
			writer.XmlSummary(
				$"Registers every validator the ZodSharp source generator produced for this assembly.",
				"Trim- and AOT-safe: each validator is named directly, so nothing is discovered through metadata."
			);
			using (
				writer.ClassScope(
					new TypeDeclarationOptions(className, TypeDeclarationAccessibility.Public) { IsStatic = true }
				)
			)
			{
				writer.XmlSummary("Registers every generated validator in this assembly into the factory.");
				writer.XmlParam("factory", "The factory to register into.");
				writer.XmlReturn("The factory, for chaining.");
				using (writer.OpenBlockScope($"public static {factoryType} Register({factoryType} factory)"))
				{
					writer.IfBlock(
						"factory is null",
						body => body.Line("throw new global::System.ArgumentNullException(nameof(factory));")
					);

					foreach (var schema in registrable)
					{
						writer.MethodCallOn(
							"factory",
							$"Register<{schema.TargetType.AsTypeReference()}>",
							$"new global::{GetValidatorTypeName(schema)}()"
						);
					}

					writer.Return("factory");
				}
			}
		}

		if (model.Context.Capabilities.HasServiceCollection)
		{
			writer.NewLine();
			using (writer.BlockNamespaceScope("Microsoft.Extensions.DependencyInjection"))
			{
				writer.XmlSummary(
					$"Registers the validators the ZodSharp source generator produced for this assembly with dependency injection."
				);
				using (
					writer.ClassScope(
						new TypeDeclarationOptions(
							$"{identifier}ZodSharpServiceCollectionExtensions",
							TypeDeclarationAccessibility.Public
						)
						{
							IsStatic = true,
						}
					)
				)
				{
					writer.XmlSummary(
						"Adds every generated validator in this assembly to the IZodSchemaFactory registered by",
						"AddZodSharpFactory (which this call also registers when it is missing)."
					);
					writer.XmlParam("services", "The service collection.");
					writer.XmlReturn("The service collection, for chaining.");
					writer.Line(
						$"public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddZodSharp{identifier}Schemas(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services) => services.AddZodSchemaRegistration(static factory => global::{RegistrationNamespace}.{className}.Register(factory));"
					);
				}
			}
		}

		context.AddSource("ZodSharpSchemaRegistration.g.cs", writer);
	}

	/// <summary>
	/// Turns an assembly name into a PascalCase identifier: <c>Contoso.Orders.Api</c> becomes
	/// <c>ContosoOrdersApi</c>.
	/// </summary>
	internal static string GetAssemblyIdentifier(string? assemblyName)
	{
		if (string.IsNullOrWhiteSpace(assemblyName))
			return "Assembly";

		StringBuilder builder = new(assemblyName!.Length);
		var upperNext = true;
		foreach (var c in assemblyName)
		{
			if (!char.IsLetterOrDigit(c) && c != '_')
			{
				upperNext = true;
				continue;
			}

			builder.Append(upperNext ? char.ToUpperInvariant(c) : c);
			upperNext = false;
		}

		if (builder.Length == 0)
			return "Assembly";

		if (char.IsDigit(builder[0]))
			builder.Insert(0, '_');

		return builder.ToString();
	}
}
