partial class ZodSchemaGenerator
{
	const string TypeMemberFieldName = "TypeMember";

	const string ServiceProviderType = "global::System.IServiceProvider";

	const string CancellationTokenType = "global::System.Threading.CancellationToken";

	static void BuildSchema(
		SchemaGenerationOutputContext outputContext,
		SourceProductionContext context,
		bool isPrimary
	)
	{
		context.CancellationToken.ThrowIfCancellationRequested();
		var writer = outputContext.Context.CreateCodeWriter();

		GenerateSchemaClass(outputContext, writer, isPrimary, context);
		context.AddSource($"{GetHintNameStem(outputContext.ZodSchema)}.g.cs", writer);

		GenerateRefinementHookDeclaration(outputContext, context);

		context.CancellationToken.ThrowIfCancellationRequested();

		if (!IsRegistrable(outputContext.ZodSchema))
			return;

		// The validator type is named here as a typeof rather than left for the consumer to rebuild from a
		// string at runtime. That is what makes RegisterFromAssembly trim- and AOT-safe: the typeof in
		// attribute metadata roots the validator, and the attribute's DynamicallyAccessedMembers annotation
		// keeps its parameterless constructor. The adapter name must match GenerateValidatorAdapter.
		var registrationWriter = outputContext.Context.CreateCodeWriter();
		registrationWriter.AutoGeneratedHeader();
		registrationWriter.Line(
			$"[assembly: global::{TypeLibrary.ZodSharp.Core.ZodSchemaGeneratedAttribute.MetadataFullName}("
				+ $"typeof({outputContext.ZodSchema.TargetType.AsTypeReference()}), "
				+ $"typeof(global::{GetValidatorTypeName(outputContext.ZodSchema)}))]"
		);

		context.AddSource($"{GetHintNameStem(outputContext.ZodSchema)}Registration.g.cs", registrationWriter);
	}

	/// <summary>
	/// Whether the schema has a DI adapter that assembly-level registration can name: a top-level primary
	/// schema with a generated <c>Validate</c> method.
	/// </summary>
	static bool IsRegistrable(ZodSchemaDescriptor schema) =>
		schema.IsPrimary && schema.ContainingTypes.Count == 0 && schema.GenerateValidateMethod;

	/// <summary>
	/// The hint-name stem of a schema's per-type outputs: the schema's namespace, containing types and name
	/// (<c>Alpha.Outer.ItemSchema</c>), so two schemas with the same simple name in different namespaces or
	/// containing types never produce the same hint name. Derived from the declaration only, so it is stable
	/// across runs.
	/// </summary>
	internal static string GetHintNameStem(ZodSchemaDescriptor schema)
	{
		System.Text.StringBuilder builder = new();
		if (!string.IsNullOrEmpty(schema.SchemaType.Namespace))
			builder.Append(schema.SchemaType.Namespace).Append('.');

		foreach (var containingType in schema.ContainingTypes)
			builder.Append(containingType.Name).Append('.');

		return builder.Append(schema.SchemaType.Name).ToString();
	}

	static string GetValidatorTypeName(ZodSchemaDescriptor schema) =>
		string.IsNullOrEmpty(schema.SchemaType.Namespace)
			? $"{schema.SchemaType.Name}Validator"
			: $"{schema.SchemaType.Namespace}.{schema.SchemaType.Name}Validator";

	/// <summary>
	/// Emits the optional <c>OnZodValidate</c> refinement hook declaration onto the target type, so the IDE
	/// offers the implementation with the generator's signature. Nothing is emitted when the target and its
	/// containing types are not all declared <c>partial</c>.
	/// </summary>
	/// <remarks>
	/// This is the only place the generator writes to a caller-owned type; it mirrors the <c>[ErrorType]</c>
	/// emitter, which also reopens a caller-owned partial class to add generated members.
	/// </remarks>
	static void GenerateRefinementHookDeclaration(
		SchemaGenerationOutputContext outputContext,
		SourceProductionContext context
	)
	{
		var hook = outputContext.ZodSchema.RefinementHook.Value;
		if (!hook.CanEmitDeclaration)
			return;

		var writer = outputContext.Context.CreateCodeWriter();
		writer.AutoGeneratedHeader();

		using (writer.BlockNamespaceScope(outputContext.ZodSchema.TargetType.AsTypeReference()))
		{
			List<CodeWriter.BlockScope> wrapperBlocks = [];

			// The chain is the containing types, outermost first, followed by the target itself.
			for (var index = 0; index < hook.DeclarationChain.Count - 1; index++)
				wrapperBlocks.Add(writer.TypeScope(hook.DeclarationChain[index]));

			writer.Type(hook.DeclarationChain[hook.DeclarationChain.Count - 1], body =>
				EmitRefinementHook(body, outputContext.ZodSchema)
			);

			foreach (var block in wrapperBlocks)
				block.Dispose();
		}

		context.AddSource($"{GetHintNameStem(outputContext.ZodSchema)}.Hooks.g.cs", writer);
	}

	/// <summary>
	/// Writes the partial <c>OnZodValidate</c> declaration the caller implements.
	/// </summary>
	static void EmitRefinementHook(CodeWriter writer, ZodSchemaDescriptor schema)
	{
		var targetType = schema.TargetType.AsTypeReference();
		TypeReference refineContextType = new(
			new TypeIdentity(
				TypeLibraryGenerator.ZodRefineContextName,
				TypeLibraryGenerator.ZodSharpSchemasNamespace,
				1
			).MakeGeneric(targetType)
		);

		writer.XmlSummary(
			"Optional ZodSharp refinement hook. Implement this partial method to add Zod-compatible",
			$"validation rules to {schema.TargetType.Name}.",
			"Issues added to the context are reported by the generated validator: Validate, Parse, the DI",
			"adapter, IValidateOptions, and any factory that validates through the generated schema.",
			$"Use the {schema.SchemaType.Name}.Paths constants to place an issue on a member."
		);
		writer.XmlParam(
			"context",
			"The refinement context carrying the value under validation and the issues it collects."
		);

		writer.PartialMethod(
			new(TypeLibraryGenerator.ZodRefinementHookName) { Parameters = [new("context", refineContextType)] }
		);

		// A classic partial method is private, and the generated schema lives in a different type, so it
		// cannot call the hook directly. This internal bridge keeps the hook optional (an unimplemented
		// partial method elides the call entirely) while giving the schema a call target.
		writer.NewLine();
		writer.XmlSummary(
			"Invokes the optional ZodSharp refinement hook when it is implemented.",
			"Generated for the schema validator to call; not part of the type's own API."
		);
		writer.Method(
			new MethodDeclarationOptions(
				TypeLibraryGenerator.ZodRefinementHookInvokerName,
				TypeDeclarationAccessibility.Internal
			)
			{
				IsStatic = true,
				Parameters = [new("value", targetType), new("context", refineContextType)],
			},
			body => body.MethodCall($"value.{TypeLibraryGenerator.ZodRefinementHookName}", "context")
		);
	}

	static void GenerateSchemaClass(
		SchemaGenerationOutputContext outputContext,
		CodeWriter writer,
		bool isPrimary,
		SourceProductionContext context
	)
	{
		var cancellationToken = context.CancellationToken;
		cancellationToken.ThrowIfCancellationRequested();

		var schema = outputContext.ZodSchema;

		writer.AutoGeneratedHeader();
		writer
			.Using("System")
			.Using("System.Collections.Generic")
			.Using("System.Collections.Immutable")
			.Using("System.Linq")
			.Using(TypeLibraryGenerator.ZodSharpCoreNamespace)
			.NewLine();

		using (writer.BlockNamespaceScope(schema.TargetType.AsTypeReference()))
		{
			writer.XmlSummary(
				$"Auto-generated schema validator for {CodeWriter.XmlSee(schema.TargetType.Name)}.",
				"This class is generated at compile time for zero-allocation validation."
			);

			List<CodeWriter.BlockScope> wrapperBlocks = [];
			foreach (var containingTypeDeclaration in schema.ContainingTypes)
				wrapperBlocks.Add(writer.TypeScope(containingTypeDeclaration));

			using (
				writer.ClassScope(
					new TypeDeclarationOptions(schema.SchemaType, schema.TargetAccessibility)
					{
						IsPartial = true,
						IsStatic = true,
					}
				)
			)
			{
				writer.Field(
					new FieldDeclarationOptions(
						"EmptyPath",
						new TypeReference(new TypeIdentity("ZodPath", TypeLibraryGenerator.ZodSharpCoreNamespace)),
						TypeDeclarationAccessibility.Private
					)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer = $"{ZodPathType}.Root",
					}
				);

				GeneratePathsClass(writer, schema, cancellationToken);
				GenerateJsonNamesClass(writer, schema, cancellationToken);
				GenerateStaticAttributeFields(writer, schema, cancellationToken);

				if (schema.GenerateJsonSchema)
					GenerateJsonSchemaMethod(writer, schema, cancellationToken);

				if (schema.GenerateValidateMethod)
				{
					GenerateMemberFields(writer, outputContext, cancellationToken);
					GenerateValidateMethods(writer, outputContext, cancellationToken);
					GenerateMemberValidationMethods(writer, outputContext, cancellationToken);
					GenerateResolutionMethods(writer, outputContext, cancellationToken);

					if (schema.GenerateParseMethod)
						GenerateParseMethod(writer, schema, cancellationToken);

					if (schema.EnableComposition)
						GenerateCompositionMethods(writer, schema, cancellationToken);
				}
			}

			if (isPrimary && schema.GenerateValidateMethod)
			{
				GenerateValidatorAdapter(writer, outputContext, cancellationToken);

				if (
					schema.GenerateIValidateOptions == true
					&& outputContext.Context.Capabilities.HasIValidateOptions
					&& !schema.IsValueType
					&& !schema.HasOptionsValidatorConflict
				)
				{
					GenerateIValidateOptionsValidator(writer, outputContext, cancellationToken);
				}
			}

			foreach (var block in wrapperBlocks)
				block.Dispose();
		}
	}

	static void GenerateValidatorAdapter(
		CodeWriter writer,
		SchemaGenerationOutputContext outputContext,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var schema = outputContext.ZodSchema;
		var adapterName = $"{schema.SchemaType.Name}Validator";
		var schemaName = schema.SchemaType.Name;
		var targetType = schema.TargetType.AsTypeReference();
		var resultType = TypeLibrary.ZodSharp.Core.ValidationResult.MakeGeneric(schema.TargetType).AsTypeReference();
		var resultTaskReference = TypeLibraryGenerator
			.ValueTask.MakeGeneric(TypeLibrary.ZodSharp.Core.ValidationResult.MakeGeneric(schema.TargetType))
			.AsTypeReference();
		var cancellationTokenReference = TypeLibraryGenerator.CancellationToken.AsTypeReference();
		TypeReference zodPathReference = new(new TypeIdentity("ZodPath", TypeLibraryGenerator.ZodSharpCoreNamespace));
		var errorsType = "global::System.Collections.Immutable.ImmutableArray<global::ZodSharp.Core.ValidationError>";
		var baseType = TypeLibrary.ZodSharp.Core.IZodSchemaValidator.MakeGeneric(schema.TargetType).AsTypeReference();
		var usesAdapterInstance =
			schema.CustomValidationMethod.Value.InvocationKind
			== CustomValidationInvocationKind.DefinedOnSchemaValidator;

		List<TypeReference> interfaces =
		[
			new(
				new TypeIdentity("IZodMemberValidator", TypeLibraryGenerator.ZodSharpCoreNamespace, 1).MakeGeneric(
					schema.TargetType
				)
			),
			new(
				new TypeIdentity("IZodMemberResolver", TypeLibraryGenerator.ZodSharpCoreNamespace, 1).MakeGeneric(
					schema.TargetType
				)
			),
			new(new TypeIdentity("IZodUntypedValidator", TypeLibraryGenerator.ZodSharpCoreNamespace)),
			new(new TypeIdentity("IZodJsonPathMapper", TypeLibraryGenerator.ZodSharpCoreNamespace)),
		];
		if (schema.GenerateJsonSchema)
			interfaces.Add(JsonSchemaProviderIdentity.AsTypeReference());

		writer.XmlSummary(
			$"DI-friendly validator adapter for {schema.TargetType.Name}, delegating to {schemaName}.",
			"Implements member validation, member resolution and the untyped validator contract, so hosts",
			"(Blazor, Microsoft.Extensions.Validation, endpoint filters) need no reflection."
		);

		writer.Class(
			new TypeDeclarationOptions(adapterName)
			{
				Accessibility = schema.TargetAccessibility,
				IsPartial = true,
				BaseType = baseType,
				Interfaces = [.. interfaces],
			},
			body =>
			{
				body.XmlSummary("Validates an instance of the target type, returning a ValidationResult.")
					.XmlParam("value", "The value to validate.")
					.XmlReturn("ValidationResult indicating success or failure of the validation.")
					.Method(
						new MethodDeclarationOptions("Validate", resultType, TypeDeclarationAccessibility.Public)
						{
							Parameters = [new ParameterDeclarationOptions("value", targetType)],
						},
						methodBody => methodBody.Return($"{schemaName}.Validate(value)")
					);

				var instanceArgument = usesAdapterInstance ? ", this" : string.Empty;

				body.XmlSummary(
						"Asynchronously validates an instance of the target type, returning a ValidationResult."
					)
					.XmlParam("value", "The value to validate.")
					.XmlParam("cancellationToken", "The cancellation token.")
					.XmlReturn("ValidationResult indicating success or failure of the validation.")
					.Method(
						new MethodDeclarationOptions(
							"ValidateAsync",
							resultTaskReference,
							TypeDeclarationAccessibility.Public
						)
						{
							Parameters =
							[
								new("value", targetType),
								new("cancellationToken", cancellationTokenReference) { DefaultValue = "default" },
							],
						},
						methodBody =>
							methodBody.Return(
								$"{schemaName}.ValidateCoreAsync(value, null, 0, cancellationToken{instanceArgument})"
							)
					);

				body.XmlSummary(
						"Asynchronously validates an instance of the target type with the caller's services, so",
						"service-aware rules run, returning a ValidationResult."
					)
					.XmlParam("value", "The value to validate.")
					.XmlParam("services", "The caller's services.")
					.XmlParam("cancellationToken", "The cancellation token.")
					.XmlReturn("ValidationResult indicating success or failure of the validation.")
					.Method(
						new MethodDeclarationOptions(
							"ValidateAsync",
							resultTaskReference,
							TypeDeclarationAccessibility.Public
						)
						{
							Parameters =
							[
								new("value", targetType),
								new(
									"services",
									new TypeIdentity(typeof(IServiceProvider)).AsTypeReference().Nullable(body)
								),
								new("cancellationToken", cancellationTokenReference) { DefaultValue = "default" },
							],
						},
						methodBody =>
							methodBody.Return(
								$"{schemaName}.ValidateCoreAsync(value, services, 0, cancellationToken{instanceArgument})"
							)
					);

				body.XmlSummary("Gets whether some rules only run asynchronously.")
					.PropertyExpression(
						"RequiresAsyncValidation",
						PurviewTypeLibrary.System.Boolean,
						TypeDeclarationAccessibility.Public,
						expression => expression.Write($"{schemaName}.RequiresAsyncValidation")
					)
					.NewLine();

				body.XmlSummary("Gets whether the member has rules that ValidateMember runs.")
					.XmlParam("memberName", "The C# member name.")
					.XmlReturn("True when the member is individually validatable.")
					.MethodExpression(
						"IsValidatableMember",
						PurviewTypeLibrary.System.Boolean,
						TypeDeclarationAccessibility.Public,
						expression => expression.Write($"{schemaName}.IsValidatableMember(memberName)"),
						declaration =>
							declaration with
							{
								Parameters = [new("memberName", PurviewTypeLibrary.System.String)],
							}
					)
					.NewLine();

				body.XmlSummary("Validates one member of the value, without recursing into nested schemas.")
					.XmlParam("value", "The containing object.")
					.XmlParam("memberName", "The C# member name.")
					.XmlReturn("The member's errors.")
					.MethodExpression(
						"ValidateMember",
						resultType,
						TypeDeclarationAccessibility.Public,
						expression => expression.Write($"{schemaName}.ValidateMember(value, memberName)"),
						declaration =>
							declaration with
							{
								Parameters =
								[
									new("value", targetType),
									new("memberName", PurviewTypeLibrary.System.String),
								],
							}
					)
					.NewLine();

				body.XmlSummary("Validates one member of the value asynchronously, including its asynchronous rules.")
					.XmlParam("value", "The containing object.")
					.XmlParam("memberName", "The C# member name.")
					.XmlParam("services", "The caller's services, if any.")
					.XmlParam("cancellationToken", "The cancellation token.")
					.XmlReturn("The member's errors.")
					.MethodExpression(
						"ValidateMemberAsync",
						resultTaskReference,
						TypeDeclarationAccessibility.Public,
						expression =>
							expression.Write(
								$"{schemaName}.ValidateMemberAsync(value, memberName, services, cancellationToken)"
							),
						declaration =>
							declaration with
							{
								Parameters =
								[
									new("value", targetType),
									new("memberName", PurviewTypeLibrary.System.String),
									new(
										"services",
										new TypeIdentity(typeof(IServiceProvider)).AsTypeReference().Nullable(body)
									)
									{
										DefaultValue = "null",
									},
									new("cancellationToken", cancellationTokenReference) { DefaultValue = "default" },
								],
							}
					)
					.NewLine();

				body.XmlSummary("Resolves the object that owns the last member of an error path.")
					.XmlParam("value", "The root value.")
					.XmlParam("path", "The error path.")
					.XmlParam("container", "The owning object.")
					.XmlParam("memberName", "The owning member name.")
					.XmlReturn("True when the full path was followed.")
					.MethodExpression(
						"TryResolveMember",
						PurviewTypeLibrary.System.Boolean,
						TypeDeclarationAccessibility.Public,
						expression =>
							expression.Write(
								$"{schemaName}.TryResolveMember(value, path, out container, out memberName)"
							),
						declaration =>
							declaration with
							{
								Parameters =
								[
									new("value", targetType),
									new("path", zodPathReference),
									new("container", new TypeIdentity(typeof(object)).AsTypeReference().Nullable(body))
									{
										Modifier = ParameterModifier.Out,
									},
									new("memberName", PurviewTypeLibrary.System.String.AsTypeReference())
									{
										Modifier = ParameterModifier.Out,
									},
								],
							}
					)
					.NewLine();

				body.XmlSummary("Renames the member segments of an error path to their JSON names.")
					.XmlParam("path", "The error path.")
					.XmlParam("namingPolicy", "The naming policy for members without an explicit JSON name.")
					.XmlReturn("The renamed path.")
					.MethodExpression(
						"ToJsonNamedPath",
						zodPathReference,
						TypeDeclarationAccessibility.Public,
						expression => expression.Write($"{schemaName}.ToJsonNamedPath(path, namingPolicy)"),
						declaration =>
							declaration with
							{
								Parameters =
								[
									new("path", zodPathReference),
									new(
										"namingPolicy",
										new TypeIdentity(typeof(Func<string, string>)).AsTypeReference().Nullable(body)
									)
									{
										DefaultValue = "null",
									},
								],
							}
					)
					.NewLine();

				// The untyped contract is implemented explicitly, so the typed members stay the ones callers see.
				body.Line(
						"global::System.Type global::ZodSharp.Core.IZodUntypedValidator.ValidatedType => typeof("
							+ targetType
							+ ");"
					)
					.NewLine();

				using (
					body.OpenBlockScope(
						$"{errorsType} global::ZodSharp.Core.IZodUntypedValidator.Validate(object? value)"
					)
				)
				{
					body.Assignment("var", "result", $"{schemaName}.Validate(Cast(value))");
					body.Return("result.IsSuccess ? [] : result.Errors");
				}

				body.NewLine();
				// An explicit interface implementation cannot carry an accessibility modifier, and the
				// structured member APIs always emit one, so these stay raw text.
#pragma warning disable PSGFR19 // Prefer a structured CodeWriter statement API
				body.Line(
					$"global::System.Threading.Tasks.ValueTask<{errorsType}> global::ZodSharp.Core.IZodUntypedValidator.ValidateAsync(object? value, {ServiceProviderType}? services, {CancellationTokenType} cancellationToken) => {GeneratedValidation}.ToErrorsAsync({schemaName}.ValidateCoreAsync(Cast(value), services, 0, cancellationToken{instanceArgument}));"
				);
				body.NewLine();
				body.Line(
					$"global::System.Threading.Tasks.ValueTask<{errorsType}> global::ZodSharp.Core.IZodUntypedValidator.ValidateMemberAsync(object value, string memberName, {ServiceProviderType}? services, {CancellationTokenType} cancellationToken) => {GeneratedValidation}.ToErrorsAsync({schemaName}.ValidateMemberAsync(Cast(value), memberName, services, cancellationToken));"
				);

				body.NewLine();
				body.Line(
					$"bool global::ZodSharp.Core.IZodUntypedValidator.TryResolveMember(object value, {ZodPathType} path, out object? container, out string memberName) => {schemaName}.TryResolveMember(Cast(value), path, out container, out memberName);"
				);
#pragma warning restore PSGFR19
				body.NewLine();

				if (usesAdapterInstance)
				{
					var custom = schema.CustomValidationMethod.Value;
					var servicesArgument = custom.RequiresServices ? ", services" : string.Empty;
					body.XmlSummary("Invokes the custom validation method for the generated schema.");
					body.MethodExpression(
						CustomValidationBridgeName,
						resultTaskReference,
						TypeDeclarationAccessibility.Internal,
						expression =>
							expression.Write($"{custom.MethodName}(value{servicesArgument}, cancellationToken)"),
						declaration =>
							declaration with
							{
								Parameters = custom.RequiresServices
									?
									[
										new("value", targetType),
										new("services", new TypeIdentity(typeof(IServiceProvider)).AsTypeReference()),
										new("cancellationToken", cancellationTokenReference),
									]
									: [new("value", targetType), new("cancellationToken", cancellationTokenReference)],
							}
					);
					body.NewLine();
				}

				using (body.OpenBlockScope($"static {targetType} Cast(object? value)"))
				{
					body.IfBlock($"value is {targetType} typed", ifBody => ifBody.Return("typed"));
					if (schema.TargetCanBeNull)
						body.IfBlock("value is null", ifBody => ifBody.Return("default!"));
					body.Throw(
						$"new global::System.ArgumentException($\"Value of type '{{value?.GetType().FullName}}' cannot be validated as '{schema.TargetType.Name}'.\", nameof(value))"
					);
				}

				if (!schema.GenerateJsonSchema)
					return;

				body.NewLine();
				body.XmlSummary(
						"Builds the JSON Schema (Draft 2020-12) definition for the target type.",
						"Delegates to the generated schema, so an attribute-generated validator can be exported."
					)
					.XmlReturn("The JSON Schema definition.")
					.Method(
						new MethodDeclarationOptions(
							"BuildJsonSchema",
							JsonSchemaDefinitionIdentity.AsTypeReference(),
							TypeDeclarationAccessibility.Public
						),
						methodBody => methodBody.Return($"{schemaName}.BuildJsonSchema()")
					);
			}
		);
	}

	/// <summary>
	/// Emits <c>{Type}Validator : IValidateOptions&lt;T&gt;</c> and, when .NET 11's
	/// <c>IAsyncValidateOptions&lt;T&gt;</c> resolves and the type has asynchronous rules, the async interface
	/// too. Failures read <c>{path}: {message} ({code})</c>, so the setting at fault can be found.
	/// </summary>
	static void GenerateIValidateOptionsValidator(
		CodeWriter writer,
		SchemaGenerationOutputContext outputContext,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var schema = outputContext.ZodSchema;
		var validatorName = $"{schema.TargetType.Name}Validator";
		var targetType = schema.TargetType.AsTypeReference();
		var baseType = TypeLibrary
			.Microsoft.Extensions.Options.IValidateOptions.MakeGeneric(schema.TargetType)
			.AsTypeReference();
		var validateOptionsResult = TypeLibrary.Microsoft.Extensions.Options.ValidateOptionsResult.AsTypeReference();
		var nullableString = PurviewTypeLibrary.System.String.AsTypeReference().Nullable(writer);
		var emitAsync =
			outputContext.Context.Capabilities.HasIAsyncValidateOptions && outputContext.RequiresAsync(schema);

		writer.XmlSummary(
			$"Validates {CodeWriter.XmlSee(schema.TargetType.Name)} via the source-generated schema, for use with Microsoft.Extensions.Options.",
			emitAsync
				? "The synchronous Validate runs the synchronous rules; ValidateAsync (used by ValidateOnStart) runs every rule."
				: "Each failure reads '{path}: {message} ({code})'."
		);

		writer.Class(
			new TypeDeclarationOptions(validatorName)
			{
				Accessibility = schema.TargetAccessibility,
				IsSealed = true,
				BaseType = baseType,
				Interfaces = emitAsync
					?
					[
						new TypeReference(
							new TypeIdentity("IAsyncValidateOptions", "Microsoft.Extensions.Options", 1).MakeGeneric(
								schema.TargetType
							)
						),
					]
					: [],
			},
			body =>
			{
				body.XmlSummary("Validates the options instance against the source-generated schema.")
					.XmlParam("name", "The options name (unused by schema validation).")
					.XmlParam("options", "The options instance to validate.")
					.XmlReturn("A ValidateOptionsResult indicating success or the validation failure messages.")
					.Method(
						new MethodDeclarationOptions(
							"Validate",
							validateOptionsResult,
							TypeDeclarationAccessibility.Public
						)
						{
							Parameters =
							[
								new ParameterDeclarationOptions("name", nullableString),
								new ParameterDeclarationOptions("options", targetType),
							],
						},
						method =>
						{
							method.Assignment("var", "schemaResult", $"{schema.SchemaType.Name}.Validate(options)");
							method.IfBlock("schemaResult.IsSuccess", ifBody =>
								ifBody.Return($"{validateOptionsResult}.Success")
							);
							method.NewLine();
							method.Return(
								$"{validateOptionsResult}.Fail(schemaResult.Errors.Select(static error => {GeneratedValidation}.FormatOptionsFailure(error)))"
							);
						}
					);

				if (!emitAsync)
					return;

				body.NewLine();
				body.XmlSummary("Validates the options instance against every rule of the source-generated schema.")
					.XmlParam("name", "The options name (unused by schema validation).")
					.XmlParam("options", "The options instance to validate.")
					.XmlParam("cancellationToken", "The cancellation token.")
					.XmlReturn("A ValidateOptionsResult indicating success or the validation failure messages.");
				using (
					body.OpenBlockScope(
						$"public async global::System.Threading.Tasks.Task<{validateOptionsResult}> ValidateAsync(string? name, {targetType} options, {CancellationTokenType} cancellationToken = default)"
					)
				)
				{
					body.Assignment(
						"var",
						"schemaResult",
						$"await {schema.SchemaType.Name}.ValidateAsync(options, null, cancellationToken).ConfigureAwait(false)"
					);
					body.IfBlock("schemaResult.IsSuccess", ifBody => ifBody.Return($"{validateOptionsResult}.Success"));
					body.NewLine();
					body.Return(
						$"{validateOptionsResult}.Fail(schemaResult.Errors.Select(static error => {GeneratedValidation}.FormatOptionsFailure(error)))"
					);
				}
			}
		);

		writer.NewLine();
	}

	static void GenerateParseMethod(CodeWriter writer, ZodSchemaDescriptor schema, CancellationToken cancellationToken)
	{
		cancellationToken.ThrowIfCancellationRequested();

		writer
			.XmlSummary("Validates and returns the value, throwing an exception if validation fails.")
			.XmlParam("value", "The value to validate and return.")
			.XmlReturn("The validated value.");

		MethodDeclarationOptions methodDeclaration = new(
			"Parse",
			schema.TargetType.AsTypeReference(),
			TypeDeclarationAccessibility.Public
		)
		{
			IsStatic = true,
			Parameters = [new("value", schema.TargetType.AsTypeReference())],
		};

		writer.Method(methodDeclaration, methodBody => methodBody.Return("Validate(value).GetValueOrThrow()"));
	}

	static void GenerateCompositionMethods(
		CodeWriter writer,
		ZodSchemaDescriptor schema,
		CancellationToken cancellationToken
	)
	{
		cancellationToken.ThrowIfCancellationRequested();

		var validationResultType = TypeLibrary
			.ZodSharp.Core.ValidationResult.MakeGeneric(schema.TargetType)
			.AsTypeReference();
		var targetType = schema.TargetType.AsTypeReference();
		var funcType = PurviewTypeLibrary
			.System.Func.WithArity(2)
			.MakeGeneric(schema.TargetType, PurviewTypeLibrary.System.Boolean)
			.AsTypeReference();
		var stringType = PurviewTypeLibrary.System.String.MakeNullable(writer);

		// A failed predicate is a refinement: the same refinement_failed code and custom category the runtime
		// ZodRefinement reports.
		void WriteFailure(CodeWriter body, string fallbackMessage) =>
			body.Return(
				$"{validationResultType}.Failure(global::ZodSharp.Core.ZodIssues.RefinementFailed(message ?? {fallbackMessage.StringLiteral()}, EmptyPath))"
			);

		writer
			.Line()
			.XmlSummary(
				"Validates the value and then requires an additional predicate to pass (value-first .and()).",
				"Equivalent to Zod's .and() semantics applied to a value."
			)
			.Method(
				new("ApplyAnd", validationResultType, TypeDeclarationAccessibility.Public)
				{
					IsStatic = true,
					Parameters =
					[
						new("value", targetType),
						new("additionalValidation", funcType),
						new("message", stringType) { DefaultValue = "null" },
					],
				},
				method =>
				{
					method.Assignment("var", "result", "Validate(value)");

					method.IfBlock("!result.IsSuccess", ifBody => ifBody.Return("result"));
					method.NewLine();
					method.IfBlock("!additionalValidation(value)", ifBody =>
						WriteFailure(ifBody, $"Additional validation failed for {schema.TargetType.Name}")
					);
					method.NewLine();
					method.Return("result");
				}
			);

		writer.NewLine();
		writer
			.XmlSummary(
				"Validates the value and accepts it if either the schema or an alternative predicate passes (value-first .or()).",
				"Equivalent to Zod's .or() semantics applied to a value."
			)
			.Method(
				new MethodDeclarationOptions("ApplyOr", validationResultType, TypeDeclarationAccessibility.Public)
				{
					IsStatic = true,
					Parameters =
					[
						new("value", targetType),
						new("alternativeValidation", funcType),
						new("message", stringType) { DefaultValue = "null" },
					],
				},
				method =>
				{
					method.Assignment("var", "result", "Validate(value)");
					method.IfBlock("result.IsSuccess", ifBody => ifBody.Return("result"));
					method.NewLine();
					method.IfBlock("alternativeValidation(value)", ifBody =>
						ifBody.Return($"{validationResultType}.Success(value)")
					);
					method.NewLine();
					WriteFailure(method, $"Neither validation passed for {schema.TargetType.Name}");
				}
			);

		writer.NewLine();
		writer
			.XmlSummary(
				"Validates the value and then runs a custom refinement predicate (value-first .refine()).",
				"Equivalent to Zod's .refine() semantics applied to a value."
			)
			.Method(
				new("ApplyRefine", validationResultType, TypeDeclarationAccessibility.Public)
				{
					IsStatic = true,
					Parameters =
					[
						new("value", targetType),
						new("refinement", funcType),
						new("message", stringType) { DefaultValue = "null" },
					],
				},
				method =>
				{
					method.Assignment("var", "result", "Validate(value)");
					method.IfBlock("!result.IsSuccess", ifBody => ifBody.Return("result"));
					method.NewLine();
					method.IfBlock("!refinement(value)", ifBody =>
						WriteFailure(ifBody, $"Refinement validation failed for {schema.TargetType.Name}")
					);
					method.NewLine();
					method.Return("result");
				}
			);

		writer.NewLine();
	}

	static void GenerateStaticAttributeFields(
		CodeWriter writer,
		ZodSchemaDescriptor schema,
		CancellationToken cancellationToken
	)
	{
		var regexType = new TypeIdentity("Regex", "System.Text.RegularExpressions").AsTypeReference();

		foreach (var property in schema.Properties)
		{
			cancellationToken.ThrowIfCancellationRequested();
			if (!property.ShouldProcess)
				continue;

			var prop = property.Value;

			if (prop.ValidationAttributes.RegularExpression.ShouldProcess)
			{
				var regex = prop.ValidationAttributes.RegularExpression.Value;
				var pattern = regex.Pattern ?? string.Empty;

				// The pattern is author-supplied but runs against untrusted request input, so it carries a match
				// timeout: the attribute's own MatchTimeoutInMilliseconds (2s by default, as RegexRule uses).
				// Without it a catastrophically backtracking pattern hangs the request thread.
				var timeout =
					regex.MatchTimeoutInMilliseconds > 0
						? $"global::System.TimeSpan.FromMilliseconds({regex.MatchTimeoutInMilliseconds.ToString(System.Globalization.CultureInfo.InvariantCulture)})"
						: "global::ZodSharp.Rules.RegexRule.DefaultMatchTimeout";
				writer.Field(
					new(GetRegexFieldName(prop.Name), regexType, TypeDeclarationAccessibility.Private)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer =
							$"new({pattern.StringLiteral()}, global::System.Text.RegularExpressions.RegexOptions.CultureInvariant, {timeout})",
					}
				);
			}

			if (prop.ValidationAttributes.Range.ShouldProcess)
			{
				var propertyType = prop.PropertyType.AsTypeReference();
				var range = prop.ValidationAttributes.Range.Value;
				writer.Field(
					new(GetRangeMinimumFieldName(prop.Name), propertyType, TypeDeclarationAccessibility.Private)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer = range.MinimumExpression,
					}
				);
				writer.Field(
					new(GetRangeMaximumFieldName(prop.Name), propertyType, TypeDeclarationAccessibility.Private)
					{
						IsStatic = true,
						IsReadOnly = true,
						Initializer = range.MaximumExpression,
					}
				);
			}
		}

		writer.NewLine();
	}
